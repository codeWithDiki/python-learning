# Sama Dengan

x = 5
y = 5

print(f"Hasil perbandingan sama dengan dari x dan y : {x == y}")

# Tidak Sama Dengan

x = 5
y = 3

print(f"Hasil dari perbandingan tidak sama dengan dari x dan y : {x != y}")

# Lebih Besar Dari

x = 5
y = 3

print(f"Hasil dari lebih besar dari x dan y : {x > y}")

# Lebih Kecil Dari

x = 3
y = 5

print(f"Hasil dari lebih kecil dari x dan y : {x < y}")

# Lebih Besar atau Sama Dengan

x = 5
y = 5

print(f"Hasil dari lebih besar atau sama dengan x dan y : {x >= y}")

# Lebih Kecil atau Sama Dengan

x = 5
y = 5

print(f"Hasil dari lebih kecil atau sama dengan x dan y : {x <= y}")