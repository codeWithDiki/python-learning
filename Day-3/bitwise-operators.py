# Tentukan dua angka
a = 10  # Dalam biner: 0000 1010
b = 4   # Dalam biner: 0000 0100

# 1. Bitwise AND (&)
print("a & b =", a & b)    # Hasil: 0

# 2. Bitwise OR (|)
print("a | b =", a | b)    # Hasil: 14

# 3. Bitwise XOR (^)
print("a ^ b =", a ^ b)    # Hasil: 14

# 4. Bitwise NOT (~)
print("~a =", ~a)          # Hasil: -11

# 5. Bitwise Left Shift (<<)
print("a << 2 =", a << 2)  # Hasil: 40

# 6. Bitwise Right Shift (>>)
print("a >> 2 =", a >> 2)  # Hasil: 2